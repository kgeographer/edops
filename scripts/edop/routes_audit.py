"""Classify every live /api route by the templates and static JS that call it.

Usage:  python scripts/edop/routes_audit.py [output_path]
        (default: print to stdout; docs/edop/routes_audit.txt is the usual target)

Routes come from the running FastAPI app, so the list is never stale. A route counts
as called when its literal path appears after "/api" in a template or static .js file
(every call site in this codebase is a literal string; routes with path parameters
match on the text before the first "{"). sandbox_v03.html is retired and does not
count as a live caller.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from fastapi.routing import APIRoute  # noqa: E402
from app.main import app  # noqa: E402

RETIRED = {"sandbox_v03"}


def sources():
    files = list((ROOT / "app/templates").glob("*.html")) + list((ROOT / "app/static/js").glob("*.js"))
    return {f.stem: f.read_text(errors="ignore") for f in files}


def callers(path, texts):
    prefix = path.split("{")[0]
    tail = "" if "{" in path else r"(?![A-Za-z0-9_\-/])"
    pat = re.compile(re.escape("/api" + prefix) + tail)
    return sorted(name for name, text in texts.items() if pat.search(text))


def main():
    texts = sources()
    routes = {}
    for r in app.routes:
        if isinstance(r, APIRoute) and r.path.startswith("/api/"):
            p = r.path[len("/api"):]
            routes.setdefault(p, {"methods": set(), "schema": False})
            routes[p]["methods"] |= r.methods - {"HEAD", "OPTIONS"}
            routes[p]["schema"] |= r.include_in_schema

    buckets = defaultdict(list)
    for p in sorted(routes):
        who = callers(p, texts)
        live = [w for w in who if w not in RETIRED]
        if len(live) == 1:
            buckets[f"{live[0]} only"].append(p)
        elif len(live) > 1:
            buckets["shared"].append((p, live))
        elif who:
            buckets["retired pages only"].append(p)
        else:
            buckets["no template or JS caller"].append(p)

    out = [f"ROUTES AUDIT (generated by scripts/edop/routes_audit.py)",
           f"{len(routes)} distinct /api paths. Live callers = templates and static JS other than {', '.join(sorted(RETIRED))}.",
           "Partials (_guide_*, _help_*) count as their own caller.", ""]
    for key in sorted(k for k in buckets if k.endswith(" only") and k != "retired pages only"):
        out += [f"{key}:", "  " + "  ".join(buckets[key]), ""]
    out.append("shared (more than one live caller):")
    out += [f"  {p:34s}{', '.join(w)}" for p, w in buckets["shared"]] or ["  (none)"]
    out.append("")
    for key in ("retired pages only", "no template or JS caller"):
        out += [f"{key}:"]
        out += [f"  {p:34s}{'hidden' if not routes[p]['schema'] else 'in schema'}" for p in buckets[key]] or ["  (none)"]
        out.append("")
    text = "\n".join(out)
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(text)
        print(f"wrote {sys.argv[1]} ({len(routes)} routes)")
    else:
        print(text)


if __name__ == "__main__":
    main()
